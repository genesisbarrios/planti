import type { ReadingSource } from "@/lib/types/domain";

const STYLES: Record<ReadingSource | "none", { label: string; className: string; description: string }> = {
  device: {
    label: "Live device",
    className: "border-forest/25 bg-moss-soft text-forest",
    description: "Readings measured by the connected sensor",
  },
  simulated: {
    label: "Simulated",
    className: "border-amber/30 bg-amber-soft text-amber",
    description: "Readings generated by the simulator, not measured",
  },
  manual: {
    label: "Manual entry",
    className: "border-line-strong bg-sunken text-ink-muted",
    description: "Readings entered by hand",
  },
  none: {
    label: "No data",
    className: "border-line-strong bg-sunken text-ink-muted",
    description: "No readings recorded yet",
  },
};

/** Always-visible label that tells the viewer where the numbers came from. */
export function SourceBadge({ source }: { source: ReadingSource | null }) {
  const style = STYLES[source ?? "none"];
  return (
    <span
      title={style.description}
      className={`inline-flex items-center rounded-full border px-2.5 py-0.5 font-mono text-[0.6875rem] font-medium uppercase tracking-[0.12em] ${style.className}`}
    >
      {style.label}
      <span className="sr-only">: {style.description}</span>
    </span>
  );
}
